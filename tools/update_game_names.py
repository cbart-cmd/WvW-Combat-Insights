"""Refresh the embedded names from the public GW2 API, without third-party packages."""

import concurrent.futures
import json
from pathlib import Path
import urllib.request

LANGUAGES = ("es", "en", "fr", "de")
ENDPOINTS = ("professions", "specializations", "wvw/ranks")
PROFESSIONS = (
    "Guardian", "Warrior", "Engineer", "Ranger", "Thief",
    "Elementalist", "Mesmer", "Necromancer", "Revenant",
)


def fetch(job):
    endpoint, language = job
    url = f"https://api.guildwars2.com/v2/{endpoint}?ids=all&lang={language}"
    with urllib.request.urlopen(url, timeout=60) as response:
        records = json.load(response)
    if not isinstance(records, list) or not records:
        raise ValueError(f"Invalid API response: {url}")
    return job, {record["id"]: record for record in records}


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    jobs = [(endpoint, language) for endpoint in ENDPOINTS for language in LANGUAGES]
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        data = dict(pool.map(fetch, jobs))
    for endpoint in ENDPOINTS:
        ids = set(data[endpoint, "en"])
        for language in LANGUAGES:
            if set(data[endpoint, language]) != ids:
                raise ValueError(f"Inconsistent localized IDs: {endpoint}/{language}")
    lines = [
        "// Generated by tools/update_game_names.py from https://api.guildwars2.com/v2/.",
        "// Columns: es, en, fr, de. Refresh with: python tools\\update_game_names.py",
    ]
    for name, endpoint, ids, field in [
        ("PROFESSIONS", "professions", PROFESSIONS, "name"),
        ("SPECIALIZATIONS", "specializations",
         sorted(k for k, v in data["specializations", "en"].items() if v["elite"]), "name"),
        ("WVW_RANKS", "wvw/ranks", sorted(data["wvw/ranks", "en"]), "title"),
    ]:
        lines.append(f"pub const {name}: &[(u32, [&str; 4])] = &[")
        for index, key in enumerate(ids, 1):
            identifier = index if name == "PROFESSIONS" else key
            values = [data[endpoint, language][key][field] for language in LANGUAGES]
            if not all(isinstance(value, str) and value for value in values):
                raise ValueError(f"Missing names: {endpoint}/{key}")
            lines.append(f"    ({identifier}, [{', '.join(map(quoted, values))}]),")
        lines.append("];")
    target = Path(__file__).resolve().parents[1] / "nexusbase" / "gw2" / "game_names.rs"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Updated {target}: 4 languages, 9 professions, "
          f"{len(data['specializations', 'en'])} specializations, "
          f"{len(data['wvw/ranks', 'en'])} WvW ranks.")


if __name__ == "__main__":
    main()
