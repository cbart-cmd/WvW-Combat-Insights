"""Collect dependency license texts from Cargo's local cache (stdlib only)."""

import argparse
import json
from pathlib import Path
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD-PARTY-LICENSES.txt"
NOTICE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT")
SUPPLEMENTAL_NOTICES = {
    ("bitfields", "3.1.0"): "bitfields-3.1.0-MIT.txt",
    ("bitfields-impl", "3.1.0"): "bitfields-3.1.0-MIT.txt",
    ("winapi-i686-pc-windows-gnu", "0.4.0"): "winapi-0.4.0-MIT.txt",
    ("winapi-x86_64-pc-windows-gnu", "0.4.0"): "winapi-0.4.0-MIT.txt",
}


def notice_files(directory):
    return sorted(
        path for path in directory.rglob("*")
        if path.is_file() and path.name.upper().startswith(NOTICE_PREFIXES)
    )


def collect():
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--offline", "--locked", "--format-version", "1"],
        cwd=ROOT, text=True, encoding="utf-8",
    ))
    sections = [
        "Third-party dependency licenses",
        "Generated by tools/collect_licenses.py from Cargo.lock and local package notices.",
        "Includes build and target-specific dependencies; original terms remain unchanged.",
    ]
    for package in sorted(metadata["packages"], key=lambda p: (p["name"], p["version"])):
        if package["id"] in metadata["workspace_members"]:
            continue
        directory = Path(package["manifest_path"]).parent
        files = notice_files(directory)
        base = directory
        if not files:
            base = directory.parent
            files = sorted(
                path for path in base.iterdir()
                if path.is_file() and path.name.upper().startswith(NOTICE_PREFIXES)
            )
        if not files:
            supplemental = SUPPLEMENTAL_NOTICES.get((package["name"], package["version"]))
            if supplemental:
                base = ROOT / "tools" / "licenses"
                files = [base / supplemental]
        if not files:
            raise RuntimeError(f"No license text found for {package['name']} {package['version']}")
        sections.extend([
            "",
            "=" * 72,
            f"{package['name']} {package['version']}",
            f"Source: {package['source']}",
            f"Declared license: {package['license'] or 'see bundled license text'}",
        ])
        for path in files:
            sections.extend([
                "",
                f"--- {path.relative_to(base).as_posix()} ---",
                path.read_text(encoding="utf-8-sig").strip(),
            ])
    return "\n".join(sections) + "\n"


class NoticeTests(unittest.TestCase):
    def test_includes_nested_native_notices_but_not_source_files(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / "native").mkdir()
            (root / "LICENSE-MIT").touch()
            (root / "native" / "LICENSE.txt").touch()
            (root / "native" / "source.c").touch()
            self.assertEqual(
                [path.relative_to(root).as_posix() for path in notice_files(root)],
                ["LICENSE-MIT", "native/LICENSE.txt"],
            )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if bundled notices are stale")
    parser.add_argument("--test", action="store_true", help="run the collector self-check")
    args = parser.parse_args()
    if args.test:
        result = unittest.TextTestRunner().run(
            unittest.defaultTestLoader.loadTestsFromTestCase(NoticeTests)
        )
        return 0 if result.wasSuccessful() else 1
    contents = collect()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != contents:
            raise SystemExit("Third-party notices are stale; run python tools\\collect_licenses.py")
        print("Third-party notices match the locked dependencies.")
    else:
        OUTPUT.write_text(contents, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
