"""Rebuild offline weapon metadata and official weapon-item icons (stdlib only)."""

import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
API = "https://api.guildwars2.com/v2/"
PROFESSIONS = [
    "Guardian", "Warrior", "Engineer", "Ranger", "Thief",
    "Elementalist", "Mesmer", "Necromancer", "Revenant",
]
WEAPONS = [
    "Axe", "Dagger", "Focus", "Greatsword", "Hammer", "Longbow", "Mace",
    "Pistol", "Rifle", "Scepter", "Shield", "Shortbow", "Spear", "Speargun",
    "Staff", "Sword", "Torch", "Trident", "Warhorn",
]
# Genuine alternate weapon buttons not linked from the profession's base palette.
# Transformations (Celestial Avatar, shrouds, radiant weapons), conjures, pet
# attacks and triggered damage (e.g. Unholy Burst / Radiant Fire) are not weapons.
ALTERNATES = {
    13128, 17008, 40710, 41068, 62876, 63073, 63075, 63134, 63182,
    63330, 63366, 71791, 71827, 71847, 71867, 71880, 71907, 71974,
    72051, 72079, 72904, 72913, 72932, 72993, 73017, 73030, 73044,
    73067, 73076, 73092, 73140, 73150,
}
# The original underwater spear palette and its chains/stealth/ambush variants.
# Absence of NoUnderwater is NOT enough: some generated land spear effects omit
# that flag, while the profession-level Spear entry still carries Aquatic.
AQUATIC_SPEAR_SKILLS = {
    9189, 9190, 9191, 9192, 9193, 10251, 10255, 10315, 10316, 10317,
    10318, 10325, 10616, 10617, 10619, 10692, 10693, 10694, 10695,
    12552, 12553, 12555, 12556, 12557, 12559, 12561, 12630, 13068,
    13069, 13070, 13119, 13120, 13121, 13122, 13125, 13130, 14437,
    14438, 14439, 14440, 14441, 14448, 14480, 28692, 28714, 28797,
    28815, 28827, 28915, 28930, 44864, 50379, 50417, 63065,
}


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "FightAnalysisDanger/weapon-data"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return response.read()


def api(path):
    return json.loads(fetch(API + path))


def main():
    skills = {skill["id"]: skill for skill in api("skills?ids=all&lang=en")}
    professions = api("professions?ids=all&lang=en")
    rows = {}
    for profession in professions:
        name = profession["id"]
        for weapon, palette in profession["weapons"].items():
            if weapon not in WEAPONS:
                continue
            todo = [entry["id"] for entry in palette["skills"]]
            todo += [
                skill["id"] for skill in skills.values()
                if skill["id"] in ALTERNATES
                or "Stealth Attack." in skill.get("description", "")
                or "Ambush." in skill.get("description", "")
            ]
            while todo:
                skill_id = todo.pop()
                skill = skills.get(skill_id, {})
                if (skill_id in rows or skill.get("type") != "Weapon"
                        or skill.get("weapon_type") != weapon
                        or name not in skill.get("professions", [])):
                    continue
                aquatic = weapon in ("Speargun", "Trident") or skill_id in AQUATIC_SPEAR_SKILLS
                rows[skill_id] = (weapon, PROFESSIONS.index(name) + 1, aquatic)
                todo.extend(
                    skill[key] for key in ("next_chain", "prev_chain", "flip_skill")
                    if key in skill
                )
    lines = [
        "// Generated by tools/update_weapon_data.py; do not edit the table manually.",
        "// Official API weapon palettes + chains/flips/alternate weapon buttons.",
        "// Elite specialization restrictions deliberately ignored (Weaponmaster Training).",
        "// See nexusbase/assets/weapons/sources.json for provenance and attribution.",
        "const WEAPON_SKILLS: &[(u32, &str, u32, bool)] = &[",
    ]
    lines += [
        f'    ({skill_id}, "{weapon}", {profession}, {str(aquatic).lower()}),'
        for skill_id, (weapon, profession, aquatic) in sorted(rows.items())
    ]
    lines += [
        "];", "",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct WeaponSkill {",
        "    pub weapon: &'static str,",
        "    pub profession: u32,",
        "    pub aquatic: bool,",
        "}", "",
        "pub fn metadata(skill_id: u32) -> Option<WeaponSkill> {",
        "    WEAPON_SKILLS",
        "        .binary_search_by_key(&skill_id, |&(id, _, _, _)| id)",
        "        .ok()",
        "        .map(|index| {",
        "            let (_, weapon, profession, aquatic) = WEAPON_SKILLS[index];",
        "            WeaponSkill { weapon, profession, aquatic }",
        "        })",
        "}", "",
        "#[cfg(test)]",
        "pub fn for_skill(skill_id: u32) -> Option<&'static str> {",
        "    metadata(skill_id).map(|skill| skill.weapon)",
        "}", "",
    ]
    (ROOT / "nexusbase" / "gw2" / "weapon_skills.rs").write_text("\n".join(lines), encoding="utf-8")

    # Basic real weapon item artwork, not profession/skill/trait icons.
    items = []
    for start in (30705, 30905):
        items += api("items?ids=" + ",".join(map(str, range(start, start + 200))) + "&lang=en")
    aliases = {"LongBow": "Longbow", "ShortBow": "Shortbow", "Harpoon": "Spear"}
    choices = {}
    for item in sorted(items, key=lambda item: item["id"]):
        weapon = aliases.get(item.get("details", {}).get("type"), item.get("details", {}).get("type"))
        if item.get("type") == "Weapon" and weapon in WEAPONS:
            choices.setdefault(weapon, item)
    assert set(choices) == set(WEAPONS), set(WEAPONS) - set(choices)
    destination = ROOT / "nexusbase" / "assets" / "weapons"
    destination.mkdir(parents=True, exist_ok=True)
    sources = {
        "description": "Unmodified official Guild Wars 2 basic weapon item icons, bundled for offline display; not skill icons.",
        "copyright": "Guild Wars 2 artwork © ArenaNet LLC. All rights reserved. Not CC0 or MIT.",
        "terms": "https://www.guildwars2.com/en/legal/guild-wars-2-content-terms-of-use/",
        "skill_sources": [
            API + "skills?ids=all&lang=en", API + "professions?ids=all&lang=en",
        ],
        "evtc_source": "https://www.deltaconnected.com/arcdps/evtc/README.txt",
        "weapon_set_source": "https://github.com/baaron4/GW2-Elite-Insights-Parser/blob/master/GW2EI.Library/GW2EI.Services/GW2EIEvtcParser/ParserHelpers/ArcDPSEnums.cs",
        "weapon_sets": {"land": [4, 5], "aquatic": [0, 1], "kit": 2, "transform": 3},
        "aquatic_spear_skills": sorted(AQUATIC_SPEAR_SKILLS),
        "inference_notes": [
            "Prefer direct player AnimationStart(67), legacy activations or SkillCast(result=11).",
            "Only cast-less actors fall back to positive direct strikes with matching profession/palette.",
            "Unknown/transformed/proc/pet skills are not equipped-weapon evidence.",
            "No arbitrary weapon-count cap; elite restrictions ignored for Weaponmaster Training.",
            "Spear aquatic use requires its audited underwater skill palette; land spear is not aquatic.",
            "Same-profession reflections cannot always be distinguished for cast-less sources.",
            "Incomplete animation/palette coverage can omit a weapon; no claim of a full loadout.",
        ],
        "icons": [],
    }
    for weapon in WEAPONS:
        item = choices[weapon]
        image = fetch(item["icon"])
        assert image.startswith(b"\x89PNG\r\n\x1a\n"), item["icon"]
        filename = weapon.lower() + ".png"
        (destination / filename).write_bytes(image)
        sources["icons"].append({
            "weapon": weapon, "file": filename, "item_id": item["id"],
            "item_name": item["name"], "api_url": API + "items/" + str(item["id"]) + "?lang=en",
            "image_url": item["icon"], "sha256": hashlib.sha256(image).hexdigest(),
        })
    (destination / "sources.json").write_text(json.dumps(sources, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {len(rows)} weapon skills and {len(choices)} official weapon icons.")


if __name__ == "__main__":
    main()
